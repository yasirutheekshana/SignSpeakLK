export const getSignInfo = (label: string): SignItem => {
  if (SIGN_DATABASE[label]) {
    return SIGN_DATABASE[label];
  }

  // Fallback generation for any unforeseen class
  const cleanName = label
    .replace(/^(ssl_|verbs_|additional_|months_)/, '')
    .replace(/_/g, ' ')
    .replace(/\b\w/g, c => c.toUpperCase());

  return {
    id: label,
    label,
    category: label.startsWith('verbs_')
      ? 'Verbs'
      : label.startsWith('months_')
      ? 'Months'
      : 'Sentences',
    english: cleanName,
    sinhala: cleanName,
    sinhalaPhonetic: cleanName,
    tamil: cleanName,
    gestureGuide: 'Sri Lankan Sign Language Gesture',
    icon: '🖐️',
  };
};
